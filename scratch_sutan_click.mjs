import { chromium } from 'playwright';
import fs from 'node:fs';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto('https://sutan.dev', { waitUntil: 'networkidle', timeout: 120000 });
await page.waitForTimeout(2500);
const folder = page.locator('#certificates .custom-folder').first();
await folder.scrollIntoViewIfNeeded();
await page.waitForTimeout(600);
await page.screenshot({ path: 'reference/verify-cert-folders/sutan-folder-closed.png' });
await folder.click({ force: true });
await page.waitForTimeout(1500);
const text = await page.evaluate(() => document.body.innerText.slice(-5000));
console.log('--- AFTER CLICK TEXT ---');
console.log(text);
const imgs = await page.evaluate(() => [...document.images].map(i => ({ src: i.currentSrc || i.src, alt: i.alt })).filter(i => /sosial|certificate|sertifikat/i.test(i.src + i.alt)));
console.log('--- CERT IMAGES ---', JSON.stringify(imgs, null, 1));
await page.screenshot({ path: 'reference/verify-cert-folders/sutan-folder-open.png' });
const html = await page.content();
fs.writeFileSync('scratch_sutan_after_click.html', html);
await browser.close();
